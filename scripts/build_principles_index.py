#!/usr/bin/env python3
"""Validate atomic principle frontmatter and build/check a compact retrieval index."""
from __future__ import annotations

import argparse
from pathlib import Path
import sys
import yaml

ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT / "principles"
INDEX = BASE / "INDEX.md"
REQUIRED = ("id", "title", "type", "skill", "triggers", "dependencies", "status", "question_types")
SKILLS = {"general", "reading", "listening", "writing", "speaking"}
KINDS = {"principle", "strategy", "workflow"}
STATUSES = {"draft", "reviewed", "verified"}


def atomic_files():
    for path in sorted(BASE.rglob("*.md")):
        if path.name not in {"README.md", "INDEX.md"}:
            yield path


def read_metadata(path: Path):
    data = path.read_text(encoding="utf-8")
    if not data.startswith("---\n"):
        raise ValueError(f"{path}: missing YAML frontmatter at top")
    parts = data.split("---\n", 2)
    if len(parts) < 3:
        raise ValueError(f"{path}: missing closing frontmatter delimiter")
    meta = yaml.safe_load(parts[1])
    if not isinstance(meta, dict):
        raise ValueError(f"{path}: invalid YAML metadata")
    for key in REQUIRED:
        if key not in meta:
            raise ValueError(f"{path}: missing '{key}'")
    if not isinstance(meta["id"], str) or not meta["id"].strip():
        raise ValueError(f"{path}: id must be a nonempty string")
    if not isinstance(meta["title"], str) or not meta["title"].strip():
        raise ValueError(f"{path}: title must be a nonempty string")
    if meta["skill"] not in SKILLS or meta["type"] not in KINDS or meta["status"] not in STATUSES:
        raise ValueError(f"{path}: invalid skill/type/status")
    for field in ("triggers", "dependencies", "question_types"):
        if not isinstance(meta[field], list) or not all(isinstance(v, str) and v.strip() for v in meta[field]):
            raise ValueError(f"{path}: {field} must be a list of nonempty strings")
    if meta["skill"] != "general" and not meta["triggers"]:
        raise ValueError(f"{path}: skill-specific file needs at least one trigger")
    return meta


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="Fail if INDEX.md is stale")
    args = parser.parse_args()
    rows = []
    seen = {}
    try:
        for path in atomic_files():
            meta = read_metadata(path)
            if meta["id"] in seen:
                raise ValueError(f"duplicate ID {meta['id']}: {seen[meta['id']]} and {path}")
            seen[meta["id"]] = path
            rows.append((meta["id"], meta, path.relative_to(BASE).as_posix()))
        for _, meta, path in rows:
            for dep in meta["dependencies"]:
                if dep not in seen:
                    raise ValueError(f"{path}: unknown dependency {dep}")
        rows.sort(key=lambda row: row[0])
        lines = [
            "# Principle Index",
            "",
            "> Generated by `python scripts/build_principles_index.py`. Do not edit manually.",
            "",
            "Legacy reference: [eight golden principles](general/8_golden_principles) (not yet atomized).",
            "",
            "| ID | Title | Skill | Question type(s) | Triggers | Status | File |",
            "| --- | --- | --- | --- | --- | --- | --- |",
        ]
        for code, meta, path in rows:
            vals = [code, meta["title"], meta["skill"],
                    ", ".join(meta["question_types"]) or "—",
                    ", ".join(meta["triggers"]), meta["status"], f"[open]({path})"]
            lines.append("| " + " | ".join(str(v).replace("|", "&#124;") for v in vals) + " |")
        expected = "\n".join(lines) + "\n"
        if args.check:
            if not INDEX.exists() or INDEX.read_text(encoding="utf-8") != expected:
                print("ERROR: principles/INDEX.md is stale. Run python scripts/build_principles_index.py", file=sys.stderr)
                return 1
            print(f"Validated {len(rows)} atomic principles; index up to date")
        else:
            INDEX.write_text(expected, encoding="utf-8")
            print(f"Wrote principles/INDEX.md with {len(rows)} atomic principles")
        return 0
    except (ValueError, yaml.YAMLError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
